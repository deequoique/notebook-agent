class McpAccessGrant(Base):
    """A revocable, hash-only bearer capability for the MCP adapter.

    ``grant_id`` is the stable public principal used as the MCP channel
    identity's external id.  It is deliberately unrelated to ``token_hash``
    and is safe to include in correlation metadata.  The raw bearer token is
    generated by :mod:`app.mcp_grants`, returned once, and never persisted.
    """

    __tablename__ = "mcp_access_grant"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    grant_id: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    # ``principal_id`` is a semantic alias used by transport code and audit
    # tooling; the persisted canonical column remains ``grant_id``.
    principal_id = synonym("grant_id")
    app_user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("app_user.id", ondelete="CASCADE"), nullable=False
    )
    token_hash: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    scope: Mapped[str] = mapped_column(Text, nullable=False, server_default="read")
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    disabled_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    rotated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    label: Mapped[str | None] = mapped_column(Text)
    created_by: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        CheckConstraint("scope IN ('read', 'full')", name="ck_mcp_access_grant_scope"),
        CheckConstraint(
            "label IS NULL OR length(label) <= 200",
            name="ck_mcp_access_grant_label_length",
        ),
        CheckConstraint(
            "created_by IS NULL OR length(created_by) <= 128",
            name="ck_mcp_access_grant_created_by_length",
        ),
        Index("ix_mcp_access_grant_user", "app_user_id"),
        Index("ix_mcp_access_grant_active", "grant_id", "revoked_at", "disabled_at"),
    )


# A descriptive alias is useful to callers that use the initialism as a
