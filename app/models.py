class ContentItem(Base):
    __tablename__ = "content_item"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    public_id: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        unique=True,
        server_default=text("replace(gen_random_uuid()::text, '-', '')"),
    )
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("app_user.id"), nullable=False
    )
    platform: Mapped[str] = mapped_column(platform_enum, nullable=False)
    platform_id: Mapped[str] = mapped_column(Text, nullable=False)  # video_id / bvid / sn
    kind: Mapped[str] = mapped_column(item_kind_enum, nullable=False)
    url: Mapped[str] = mapped_column(Text, nullable=False)
    title: Mapped[str | None] = mapped_column(Text)
    author: Mapped[str | None] = mapped_column(Text)
    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    duration_sec: Mapped[int | None] = mapped_column(Integer)  # video only
    char_count: Mapped[int | None] = mapped_column(Integer)  # article only
    lang: Mapped[str | None] = mapped_column(Text)  # 'en' / 'zh' -> 驱动切分阈值
    description: Mapped[str | None] = mapped_column(Text)
    tags: Mapped[list[str] | None] = mapped_column(ARRAY(Text))
    chapters: Mapped[dict | list | None] = mapped_column(JSONB)  # YouTube: [{start,end,title}]
    cover_url: Mapped[str | None] = mapped_column(Text)

    # 用户侧
    saved_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    archived_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    why_saved: Mapped[str | None] = mapped_column(Text)
    watch_state: Mapped[str | None] = mapped_column(Text, server_default="unwatched")
    watch_pos_sec: Mapped[int | None] = mapped_column(Integer)

    # 去重与溯源
    content_hash: Mapped[str | None] = mapped_column(Text)  # 正文/转录规范化后 sha256
    raw_object_key: Mapped[str | None] = mapped_column(Text)  # MinIO: 原始 json3 / HTML
    raw_format: Mapped[str] = mapped_column(
        Text, nullable=False, server_default="json3"
    )
    text_source: Mapped[str] = mapped_column(
        text_source_enum, nullable=False, server_default="none"
    )
    state: Mapped[str] = mapped_column(
        ingest_state_enum, nullable=False, server_default="pending"
    )
    fail_reason: Mapped[str | None] = mapped_column(Text)

    # Recycle-bin lifecycle.  These fields deliberately remain separate from
    # ``state``: ingestion state is owned by the worker, while deletion and
    # purge state is owned by the management/maintenance services.
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    purge_claimed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    purge_attempts: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")
    purge_error_code: Mapped[str | None] = mapped_column(Text)
    # A short-lived delete-effect fence.  Restore/re-save replaces this value
    # so a late effect from an older confirmation cannot soft-delete the item
    # again after it has become visible.
    delete_claim_token: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        UniqueConstraint(
            "user_id", "platform", "platform_id",
            name="uq_content_item_user_platform_platform_id",
        ),
        Index(
            "ix_content_item_user_saved_at",
            "user_id",
            saved_at.desc(),
            id.desc(),
            postgresql_where=text("deleted_at IS NULL"),
        ),
        Index(
            "ix_content_item_user_deleted_at",
            "user_id",
            deleted_at.desc(),
            id.desc(),
            postgresql_where=text("deleted_at IS NOT NULL"),
        ),
        Index(
            "ix_content_item_deleted_at_id",
            "deleted_at",
            id,
            postgresql_where=text("deleted_at IS NOT NULL"),
        ),
        Index("ix_content_item_saved_at", saved_at.desc()),
        Index(
            "ix_content_item_user_archived_saved_at",
            "user_id",
            "archived_at",
            saved_at.desc(),
        ),
        Index(
            "ix_content_item_content_hash",
            "content_hash",
            postgresql_where=content_hash.isnot(None),
        ),
    )


